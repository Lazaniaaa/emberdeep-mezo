// Regenerates docs/light-tuning.md: `npm run tuning` (a few minutes). Deterministic: the same seeds every run.
// It plays the real game rules with bots, so the tables cannot drift from the code. The bots are not people: they show
// how far a given amount of oil carries a descent, not how a player will feel.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { it } from "vitest";
import { BOSS_DEPTH, FLASK_LIGHT } from "../src/game/config";
import { simulateDiveRun, simulateFogRun, type BotStyle } from "../src/game/sim";
import { PROPS } from "../src/game/props";
import { DEFAULT_TUNING, countLight, lightByFloor, lightTally, resetLightTally, withTuning, type Tuning } from "../src/game/tuning";

const RUNS = 40;
const seeds = Array.from({ length: RUNS }, (_, i) => 1_000 + i * 7_919);
const avg = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
const pct = (x: number) => `${Math.round(x * 100)}%`;

type Scenario = { name: string; note: string; patch: Partial<Tuning> };
const scenarios: Scenario[] = [
  {
    name: "No creature oil",
    note: "Creatures drop no oil; jars and props as chosen.",
    patch: { killDropChance: [0, 0], killDropLight: [0, 0] },
  },
  {
    name: "Flat prop oil",
    note: "Oil's weight among a prop's loot moves only from 25 to 60 as the lantern empties (the first try, 2026-10-10).",
    patch: { propOilWeight: [25, 60] },
  },
  {
    name: "Chosen",
    note: "What the game uses.",
    patch: {},
  },
  {
    name: "+30% oil (test)",
    note: "All oil that drops (jars, props, creatures) times 1.3: the owner's local test (VITE_DROP_OIL=1.3).",
    patch: { dropOil: 1.3 },
  },
];

function dive(flasks: number, style: BotStyle = {}) {
  const rs = seeds.map(seed => simulateDiveRun(seed, flasks, undefined, undefined, style));
  const at = (d: number) => rs.filter(r => r.depth >= d).length / RUNS;
  return { depth: avg(rs.map(r => r.depth)), p3: at(3), p5: at(5), p7: at(BOSS_DEPTH) };
}

it("writes docs/light-tuning.md", { timeout: 1_800_000 }, () => {
  const out: string[] = [
    "# How much oil the deep gives back",
    "",
    "Generated by `npm run tuning` from the same code the game runs. Every number is a simulation with bots, not a measurement of players.",
    "",
    "## The question",
    "",
    `A flask holds ${FLASK_LIGHT} light and a descent may start with up to five. Exploring one of the big first floors takes about 130 steps, and a creature's blow drinks a few light more, so a floor costs roughly 130-170 light and the floors get dearer with depth. If the deep gave nothing back, two flasks would end on floor 2 or 3 and the boss on floor ${BOSS_DEPTH} could not be reached at all. If it gave too much, flasks would stop mattering and a descent would never end.`,
    "",
    "Light comes back from oil jars, broken props, defeated creatures, level-ups (+10 each), potions and chosen level perks. The separate Perk refills column includes guaranteed kill-light bonuses. Props and creatures give random oil more often the lower the lantern is. Every bot resolves free perk choices with the fixed four-slot priority in sim.ts.",
    "",
    "## How it was measured",
    "",
    `- **Diver:** a bot that only wants to go down. It fights what is in its way, picks up loot within four steps of its path, takes every stairs at once and never goes home, so it stops only when the light is gone. Where it stops is how far that oil carries a player who does not collect. The *newcomer* finds the stairs by exploring; the *expert* already knows where they are. Both dodge marked tiles; the *sloppy* one does not.`,
    `- **Collector:** the bot behind the economy report. It gathers loot and leaves when the walk home would use up its reserve. Its gold per cent spent shows how much the extra oil inflates the economy (the simulated crowd is recalibrated to it).`,
    `- ${RUNS} descents per cell, the same seeds for every scenario.`,
    "",
    "## Results",
    "",
  ];

  const results = scenarios.map(sc => withTuning(sc.patch, () => {
    const n1 = dive(1), n2 = dive(2), n3 = dive(3), n5 = dive(5);
    const e3 = dive(3, { knowsMap: true }), e5 = dive(5, { knowsMap: true });
    const s3 = dive(3, { dodge: false });
    const collector = seeds.map(seed => simulateFogRun(seed, 2));
    const gold = collector.reduce((n, r) => n + r.banked, 0) / collector.reduce((n, r) => n + r.spent, 0);
    resetLightTally();
    const divers = countLight(() => seeds.map(seed => simulateDiveRun(seed, 3)));
    const tally = Object.fromEntries(Object.entries(lightTally).map(([k, v]) => [k, v / RUNS])) as typeof lightTally;
    // Per floor, averaged over the descents that reached it.
    const floors = Array.from({ length: BOSS_DEPTH }, (_, i) => {
      const depth = i + 1, visits = divers.filter(r => r.depth >= depth).length, f = lightByFloor[depth];
      const per = Object.fromEntries(Object.entries(f ?? {}).map(([k, v]) => [k, visits ? v / visits : 0]));
      return { depth, visits, ...per } as { depth: number; visits: number } & Partial<typeof lightTally>;
    });
    return { sc, n1, n2, n3, n5, e3, e5, s3, gold, tally, floors };
  }));

  out.push(
    "### Mean floor reached, and the share of descents that reach floors 3, 5 and the boss floor",
    "",
    `| Scenario | 1 flask | 2 flasks | 3 flasks | 5 flasks | Expert, 3 flasks | Expert, 5 flasks | Sloppy, 3 flasks |`,
    `| --- | --- | --- | --- | --- | --- | --- | --- |`,
  );
  for (const r of results) {
    const cell = (x: ReturnType<typeof dive>) => `${x.depth.toFixed(1)} (${pct(x.p3)} / ${pct(x.p5)} / ${pct(x.p7)})`;
    out.push(`| **${r.sc.name}** | ${cell(r.n1)} | ${cell(r.n2)} | ${cell(r.n3)} | ${cell(r.n5)} | ${cell(r.e3)} | ${cell(r.e5)} | ${cell(r.s3)} |`);
  }
  out.push(
    "",
    "Each cell is the mean deepest floor, then the share of descents that got to floor 3 / floor 5 / floor " + BOSS_DEPTH + ". These are newcomers unless the column says expert.",
    "",
    "### Where the light came from and went, per descent (newcomer diver, 3 flasks)",
    "",
    "| Scenario | Start | Oil jars | Props | Creatures | Levels | Perk refills | Steps | Blows taken | Collector gold per cent (2 flasks) |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const r of results) {
    const t = r.tally;
    out.push(`| **${r.sc.name}** | ${3 * FLASK_LIGHT} | ${Math.round(t.jars)} | ${Math.round(t.props)} | ${Math.round(t.kills)} | ${Math.round(t.levels)} | ${Math.round(t.perks)} | -${Math.round(t.steps)} | -${Math.round(t.hits)} | ${r.gold.toFixed(2)} |`);
  }
  out.push("", "### What each scenario means", "");
  for (const r of results) out.push(`- **${r.sc.name}.** ${r.sc.note}`);

  const perFloor = (r: (typeof results)[number]) => {
    const n = (x?: number) => Math.round(x ?? 0);
    out.push(
      "| Floor | Descents there | Oil jars | Props | Creatures | **Drops** | Levels | Perk refills | Steps | Blows taken | **Net** |",
      "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const f of r.floors) {
      if (!f.visits) continue;
      const drops = (f.jars ?? 0) + (f.props ?? 0) + (f.kills ?? 0);
      const net = drops + (f.levels ?? 0) + (f.perks??0) - (f.steps ?? 0) - (f.hits ?? 0);
      out.push(`| ${f.depth} | ${f.visits} of ${RUNS} | ${n(f.jars)} | ${n(f.props)} | ${n(f.kills)} | **${n(drops)}** | ${n(f.levels)} | ${n(f.perks)} | -${n(f.steps)} | -${n(f.hits)} | **${n(net)}** |`);
    }
  };
  const chosen = results.find(r => r.sc.name === "Chosen")!;
  const test = results.find(r => r.sc.name === "+30% oil (test)")!;
  out.push(
    "",
    "### Oil per floor (newcomer diver, 3 flasks)",
    "",
    "Light gained and spent on each floor, averaged over the descents that reached it. A floor that ends a descent is spent only partly, so the deepest rows read low.",
    "",
    "**Chosen:**",
    "",
  );
  perFloor(chosen);
  out.push("", "**+30% oil (test):**", "");
  perFloor(test);

  const oils = PROPS.map(p => `${p.name} ${p.oil[0]}-${p.oil[1]}`).join(", ");
  const tick = "`";
  out.push(
    "",
    "## What was chosen, and why",
    "",
    `- **A broken prop gives one kind of loot, sometimes two** (gold, oil or crystals; a barrel always two), plus experience and, from crates, barrels and bone piles, now and then a piece of gear. Floors hold two crates instead of one and a half, and bone piles from floor 2. Oil, when it falls out: ${oils}.`,
    `- **Oil's weight among the loot swings from ${DEFAULT_TUNING.propOilWeight[0]} to ${DEFAULT_TUNING.propOilWeight[1]}** (beside gold 45 and crystals 15) as the lantern empties. With the first try, 25 to 60 ("Flat prop oil"), a delver with a full lantern found as much oil as one running dry, so the cheap-step builds went far deeper and the best build banked 3.7x an unperked delver's gold per cent (the economy tests allow 3.5x; it was 3.0x). The wide swing puts it back to about 3x and keeps the help for whoever runs dry.`,
    `- **Creatures drop ${DEFAULT_TUNING.killDropLight[0]}-${DEFAULT_TUNING.killDropLight[1]} light** with a ${pct(DEFAULT_TUNING.killDropChance[0])} chance when the lantern is full, rising to ${pct(DEFAULT_TUNING.killDropChance[1])} when it is nearly empty.`,
    `- **Oil jars hold ${DEFAULT_TUNING.oilJarLight} light; levels give +${DEFAULT_TUNING.levelLight}.**`,
    "- **A blow burns no light** (2026-10-11, the owner: only steps should): hitting a creature or a prop costs a turn but no oil; walking and waiting burn it. An urn or a sack breaks at the first blow, a crate or a barrel at the second, whatever the weapon.",
    `- **${tick}dropOil${tick} multiplies all the oil that drops** (jars, props, creatures). It is ${DEFAULT_TUNING.dropOil} for everyone; the owner can try 1.3 in local play with ${tick}VITE_DROP_OIL=1.3${tick} in ${tick}.env.local${tick}.`,
    "",
    `With the chosen values 3 flasks take a newcomer to floor ${chosen.n3.depth.toFixed(1)} on average, and ${pct(chosen.n5.p7)} of 5-flask newcomers reach Cerberus. With +30% oil the same 3 flasks reach floor ${test.n3.depth.toFixed(1)} and ${pct(test.n5.p7)} of 5-flask newcomers reach the boss; a collector banks ${test.gold.toFixed(2)} gold per cent spent instead of ${chosen.gold.toFixed(2)}, the +25% two-flask efficiency guard is checked separately on the default oil setting. The +30% setting stays a local test until the owner decides.`,
    "",
    "## What this does not show",
    "",
    "Bots are not people. A player who explores less, fights less, or remembers the floors will go further on the same oil; one who fights everything will go less far. The bots never buy potions (an Oil Vial is +30 light, a Healing Draught +60), which players will. The numbers show that the amount of oil is in a range where a descent can be carried on; they do not promise how it feels.",
    "",
  );

  writeFileSync(fileURLToPath(new URL("../docs/light-tuning.md", import.meta.url)), out.join("\n"));
});
